def parallel_steps():
    """Per sprint, numbered steps: a task sits one step after its latest same-sprint dependency, so the tasks of one
    step never depend on each other and can be done at the same time. Steps run in order."""
    order = work_order()
    sprint_of = {i: sp for i, sp, _, _ in order}
    step = {}
    for i, sp, t, ds in order:  # work order already puts dependencies first
        same = [step[d] for d in ds if sprint_of.get(d) == sp]
        step[i] = (max(same) + 1) if same else 1
    out = {}
    for i, sp, t, ds in order:
        out.setdefault(sp, {}).setdefault(step[i], []).append((i, t, ds))
    return out

