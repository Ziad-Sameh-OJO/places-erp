         "- كل سطر = **تاسك واحد تديه لحد**، و PR واحد. ابعتله لينك الـ issue.",
         "- التفاصيل في الـ issue نفسه، والكارت المذكور جنبه (`T-xx`) فيه الصورة الكبيرة. **ترتيب الشغل: [order.md](order.md).**",
