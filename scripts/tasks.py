def gh(*args, input=None):
    for attempt in range(4):
        r = subprocess.run(["gh", *args], capture_output=True, text=True, input=input)
        if r.returncode == 0: return r.stdout.strip()
        if "rate limit" in r.stderr.lower() or "timed out" in r.stderr.lower() or "502" in r.stderr: time.sleep(20 * (attempt + 1)); continue
        raise RuntimeError(f"gh {' '.join(args[:3])}: {r.stderr.strip()}")
    raise RuntimeError("gh failed after retries")

def sync_issues():
    m = json.load(open(MAP_FILE)) if os.path.exists(MAP_FILE) else {}
    for n, name, note, sprint, ts in PARTS:
        gh("label", "create", f"part:{n}", "--repo", REPO, "--color", "5319e7", "--description", f"الجزء {n} · {name}", "--force")
    gh("label", "create", "task", "--repo", REPO, "--color", "0e8a16", "--description", "تاسك صغير من docs/tasks.md (sub-issue من كارت T-xx)", "--force")
    # pass 1: make sure every task has an issue
    for n, name, sprint, t in all_tasks():
        tid, title, card = t[:3]
        if tid in m: continue
        ms = MILESTONE[task_sprint(n, sprint, t)]
        labels = ["task", f"part:{n}"] + ([CARDS[card][3]] if card in CARDS and CARDS[card][3] else [])
        args = ["issue", "create", "--repo", REPO, "--title", f"{tid} · {title}", "--body", "…", "--milestone", ms]
        for l in labels: args += ["--label", l]
        url = gh(*args)
        m[tid] = int(url.rsplit("/", 1)[1])
        json.dump(m, open(MAP_FILE, "w"), indent=1)
        print("created", tid, m[tid]); time.sleep(1.2)
    # pass 2: bodies with links between tasks
    for n, name, sprint, t in all_tasks():
        tid = t[0]
        gh("issue", "edit", str(m[tid]), "--repo", REPO, "--title", f"{tid} · {t[1]}", "--body-file", "-", input=body(n, name, sprint, t, m))
        print("body", tid); time.sleep(0.6)
    # pass 3: each task is a sub-issue of its card
    for n, name, sprint, t in all_tasks():
        tid, card = t[0], t[2]
        if card not in CARD_ISSUE: continue
        child_id = gh("api", f"repos/{REPO}/issues/{m[tid]}", "--jq", ".id")
        r = subprocess.run(["gh", "api", "-X", "POST", f"repos/{REPO}/issues/{CARD_ISSUE[card]}/sub_issues", "-F", f"sub_issue_id={child_id}"], capture_output=True, text=True)
        ok = r.returncode == 0 or "already" in (r.stdout + r.stderr).lower() or "duplicate" in (r.stdout + r.stderr).lower()
        print("sub", tid, "→", card, "ok" if ok else r.stderr.strip()[:120]); time.sleep(0.6)
    # milestones follow the work order (a task never sits in an earlier sprint than what it needs)
    for i, sp, t, _ in work_order():
        gh("issue", "edit", str(m[i]), "--repo", REPO, "--milestone", MILESTONE[sp]); time.sleep(0.4)
    write_md(m); write_order(m); write_plan_en(m)

