import type { Pair } from "./translate.ts";

// lead-rules.ts durationText («3 ساعات», «ساعتين و30 دقيقة», «45 دقيقة») and ledger.ts monthLabel («نوفمبر 2026») as
// exact pairs: they mostly arrive inside other messages, where a {placeholder}'s value is only looked up exactly, and a
// bare «{m} دقيقة» template would swallow every longer message that ends the same way.
const hoursAr = (h: number) => (h === 1 ? "ساعة" : h === 2 ? "ساعتين" : h <= 10 ? `${h} ساعات` : `${h} ساعة`);
const hoursEn = (h: number) => (h === 1 ? "1 hour" : `${h} hours`);
const durations: Pair[] = [];
for (let minutes = 1; minutes <= 72 * 60; minutes++) {
  const h = Math.floor(minutes / 60), m = minutes % 60;
  durations.push(!m ? [hoursAr(h), hoursEn(h)] : h ? [`${hoursAr(h)} و${m} دقيقة`, `${hoursEn(h)} ${m} min`] : [`${m} دقيقة`, `${m} min`]);
}
const MONTHS: Pair[] = [
  ["يناير", "January"], ["فبراير", "February"], ["مارس", "March"], ["أبريل", "April"], ["مايو", "May"], ["يونيو", "June"],
  ["يوليو", "July"], ["أغسطس", "August"], ["سبتمبر", "September"], ["أكتوبر", "October"], ["نوفمبر", "November"], ["ديسمبر", "December"],
];
const monthLabels: Pair[] = [];
for (let y = 2024; y <= 2040; y++) for (const [ar, en] of MONTHS) monthLabels.push([`${ar} ${y}`, `${en} ${y}`]);

